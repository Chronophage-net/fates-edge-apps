export async function onActivate() {
    console.log('[Patrons] Activated');
    if (!state.dataLoaded) {
        loadPatronData();
    }
    refreshView();

    // Dashboard's "View patron" links stash the target id here before
    // navigating over — see js/features/dashboard/index.js.
    const pendingPatronId = sessionStorage.getItem('fe-pending-patron-detail');
    if (pendingPatronId) {
        sessionStorage.removeItem('fe-pending-patron-detail');
        if (!state.dataLoaded) {
            await loadPatronData();
            refreshView();
        }
        window.openPatronDetailModal(pendingPatronId);
    }
}
 
export function onDeactivate() {
    console.log('[Patrons] Deactivated');
}
 
export async function refresh() {
    localStorage.removeItem('fates-edge-patrons-cache-cosmic');
    localStorage.removeItem('fates-edge-patrons-cache-terrestrial');
    localStorage.removeItem('fates-edge-patrons-cache-religion');
    await loadPatronData(true);
    refreshView();
}
 
export function destroy() {
    container = null;
}

export function revealNinth() {
    ninthRevealed = true;
    refreshView();
    showToast(i18nText("feature.patrons.theNinthHasRevealedItselfToYou", null, "🔮 The Ninth has revealed itself to you."), 'info');
}

export function isNinthRevealed() {
    return ninthRevealed;
}

