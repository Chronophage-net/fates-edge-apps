// FIX: cached patron data (saved.patrons in localStorage) can go stale
// relative to the actual /data/patrons/*.json files on disk -- e.g. after
// a content update ships but the schema version wasn't bumped, or the
// cache was written by an older session. Previously the cache-hit fast
// path in loadPatronData() would trust that cache indefinitely, so Cantor
// (and anything else reading patron rites) would silently show whatever
// was cached until the user manually hit "Refresh" (which passes
// force=true). Now the very first loadPatronData() call of the page
// session always does a real fetch, regardless of cache, so a stale
// cache can never be the reason Cantor songs don't show up. Subsequent
// calls in the same session still use the fast cache path unless the
// caller explicitly passes force=true.
let hasLoadedOnceThisSession = false;

// ─── Cross-Resonance ────────────────────────────────────────────────
// 81 rivalry pairings, extracted from the Invoker's Guide's LaTeX longtable
// into data/patron-rivalries.json (fates-edge-docs
// tools/extract_patron_rivalries.py). Only five of fifty-one patron files
// ever carried a `rivalries` key of their own, so before this the other
// seventy-odd relationships existed nowhere a tool could see them.
//
// Relationships are symmetric: the source lists each pair once, under
// whichever patron came first alphabetically. Looking a patron up has to
// check BOTH columns or half its rivals go missing -- which is exactly the
// bug a table like this invites.
let _rivalryData = null;
let _rivalryPromise = null;

export function loadRivalries() {
    if (_rivalryData) return Promise.resolve(_rivalryData);
    if (!_rivalryPromise) {
        _rivalryPromise = fetch('./data/patron-rivalries.json')
            .then(r => (r.ok ? r.json() : null))
            .then(d => { _rivalryData = d || { pairs: [], rulings: [] }; return _rivalryData; })
            .catch(() => { _rivalryData = { pairs: [], rulings: [] }; return _rivalryData; });
    }
    return _rivalryPromise;
}

/**
 * Match a patron file to a row in the rivalry table.
 *
 * The table names patrons the way a sentence does -- "Aveh",
 * "Oath of Flame & Light" -- while patron files carry long titles like
 * "Aveh, the Rider Behind the Storm". So compare on NAME KEYS: the
 * squashed full title, and the leading segment before the first comma or
 * dash, which is where a patron's actual name lives.
 *
 * A containment test alone is not enough and was the first thing tried:
 * requiring the shorter side to be five characters or more (to stop
 * "the" matching everything) silently dropped every short-named patron --
 * Aveh, Mab, Oya, Kuva, Gaila, Inaea, Isoka. Fifteen of fifty-one showed
 * no rivals at all, which looks exactly like "this patron has none".
 */
function nameKeys(value) {
    const squash = s => String(s || '')
        .toLowerCase()
        .replace(/\band\b/g, '&')
        .replace(/[^a-z0-9&]/g, '');
    const raw = String(value || '');
    const lead = raw.split(/[,\u2014\u2013]|\s+-\s+/)[0];
    return new Set([squash(raw), squash(lead)].filter(Boolean));
}

export function rivalriesFor(patron, data) {
    if (!patron || !data || !data.pairs) return [];
    const mine = new Set([
        ...nameKeys(patron.title),
        ...nameKeys(patron.name),
        ...nameKeys(String(patron.id || '').replace(/[-_]/g, ' ')),
        // Some patrons are known by more than one name and the rivalry
        // table may use either. The Ninth is listed there as "Ninth Rim",
        // its Kon'reh name, which no amount of fuzzy matching against
        // "The Ninth — Beyond Comprehension" would ever have found.
        ...(patron.also_known_as || []).flatMap(a => [...nameKeys(a)]),
    ]);
    mine.delete('');
    const matches = (name) => {
        for (const k of nameKeys(name)) {
            if (mine.has(k)) return true;
            // Fall back to containment only for names long enough that a
            // partial hit means something.
            for (const m of mine) {
                if (k.length > 6 && m.includes(k)) return true;
                if (m.length > 6 && k.includes(m)) return true;
            }
        }
        return false;
    };
    const out = [];
    for (const p of data.pairs) {
        if (matches(p.patron)) {
            out.push({ rival: p.rival, domains: p.rival_domains, loci: p.edge_loci, friction: p.friction });
        } else if (matches(p.rival)) {
            out.push({ rival: p.patron, domains: p.patron_domains, loci: p.edge_loci, friction: p.friction });
        }
    }
    return out;
}

export async function loadPatronData(force = false) {
    if (!hasLoadedOnceThisSession) {
        force = true;
    }
    hasLoadedOnceThisSession = true;

    const saved = getState();
    const cacheMatchesCurrentSchema = saved.patrons?._schemaVersion === PATRON_SCHEMA_VERSION;
    state.obligation = saved.patrons?.obligation || state.obligation;

    if (!force && saved.patrons && cacheMatchesCurrentSchema) {
        if (saved.patrons.cosmic?.length || saved.patrons.terrestrial?.length) {
            state.cosmicPatrons = (saved.patrons.cosmic || []).map(normalizePatron).sort(sortByName);
            state.terrestrialPatrons = (saved.patrons.terrestrial || []).map(normalizePatron).sort(sortByName);
            state.religions = (saved.patrons.religions || []).sort(sortByName);
            state.obligation = saved.patrons.obligation || {};
            console.log(`📦 Loaded from state: ${state.cosmicPatrons.length} cosmic, ${state.terrestrialPatrons.length} terrestrial, ${state.religions.length} religions`);
            state.dataLoaded = true;
            state.usingFallback = false;
            return;
        }
    }

    if (saved.patrons && !cacheMatchesCurrentSchema) {
        console.log(`📦 Cached patron data is schema v${saved.patrons._schemaVersion ?? 'unknown'}, current is v${PATRON_SCHEMA_VERSION} — reloading from disk.`);
    }

    await loadRemotePatrons(force);
}
 
// FIX: concurrent callers used to just check `state.isLoading` and bail
// out immediately if a load was already in flight — which meant the
// SECOND caller in the same tick (e.g. Cantor rendering right after the
// Patrons tab, or two panels both calling loadPatronData() on app start)
// would resolve its own await instantly, read getState() before the FIRST
// caller's fetch had actually finished, and render with empty/stale
// patron data. This is why Cantor (and potentially any other panel) could
// need a manual "Refresh" click on first load — by the time you clicked
// Refresh, the original fetch had long since finished, so the retry just
// worked. Concurrent callers now share and await the same promise instead
// of silently no-op'ing.
let loadingPromise = null;

// FIX: discoverPatrons() (js/core/discovery.js) keeps its own 1-hour
// localStorage cache of which patron slugs exist, checked BEFORE
// loadPatronData()'s own force-reload logic ever runs. That meant even a
// forced reload (window.refreshPatrons()/window.cantorRefresh(), or the
// very-first-call-this-session force above) still returned a stale slug
// list if discovery had cached one recently — the actual root cause of
// "Cantor needs a manual refresh to see new/changed patron rites". `force`
// is threaded through here so a real reload also bypasses discovery's cache.
async function loadRemotePatrons(force = false) {
    if (loadingPromise) return loadingPromise;

    state.isLoading = true;
    loadingPromise = (async () => {
        try {
            const cosmicSlugs = await discoverPatrons('cosmic', COSMIC_DATA_PATH, null, force);
            const terrestrialSlugs = await discoverPatrons('terrestrial', TERRESTRIAL_DATA_PATH, TERRESTRIAL_FALLBACK_DATA_PATH, force);
            const religionSlugs = await discoverPatrons('religion', RELIGION_DATA_PATH, null, force);
 
            // Fetch cosmic
            let cosmicPatrons = [];
            for (const slug of cosmicSlugs) {
                try {
                    const res = await fetch(`${COSMIC_DATA_PATH}${slug}.json`);
                    if (res.ok) {
                        const data = await res.json();
                        if (!data.id) data.id = slug;
                        // Normalize ID: replace underscores with hyphens to match expected format (e.g., defaults)
                        const normalizedId = data.id.replace(/_/g, '-');
                        data.id = normalizedId;
                        cosmicPatrons.push(normalizePatron(data));
                    }
                } catch (e) { /* ignore */ }
            }
            if (cosmicPatrons.length === 0) {
                cosmicPatrons = DEFAULT_COSMIC_PATRONS.map(normalizePatron);
                state.usingFallback = true;
                showToast(i18nText("feature.patrons.noCosmicPatronFilesFoundUsingDefaults", null, "⚠️ No cosmic patron files found. Using defaults."), 'warning');
            }
            state.cosmicPatrons = mergePatronLibrary(cosmicPatrons, getState().patrons?.cosmic).sort(sortByName);
 
            // Fetch terrestrial
            let terrestrialPatrons = [];
            for (const slug of terrestrialSlugs) {
                try {
                    let res = await fetch(`${TERRESTRIAL_DATA_PATH}${slug}.json`);
                    if (!res.ok) {
                        res = await fetch(`${TERRESTRIAL_FALLBACK_DATA_PATH}${slug}.json`);
                    }
                    if (res.ok) {
                        const data = await res.json();
                        if (!data.id) data.id = slug;
                        // Normalize ID: replace underscores with hyphens to match expected format (e.g., defaults)
                        const normalizedId = data.id.replace(/_/g, '-');
                        data.id = normalizedId;
                        terrestrialPatrons.push(normalizePatron(data));
                    }
                } catch (e) { /* ignore */ }
            }
            if (terrestrialPatrons.length === 0) {
                terrestrialPatrons = DEFAULT_TERRESTRIAL_PATRONS.map(normalizePatron);
                state.usingFallback = true;
                showToast(i18nText("feature.patrons.noTerrestrialPatronFilesFoundUsingDefaults", null, "⚠️ No terrestrial patron files found. Using defaults."), 'warning');
            }
            state.terrestrialPatrons = mergePatronLibrary(terrestrialPatrons, getState().patrons?.terrestrial).sort(sortByName);
 
            // Fetch religions
            let religions = [];
            for (const slug of religionSlugs) {
                try {
                    const res = await fetch(`${RELIGION_DATA_PATH}${slug}.json`);
                    if (res.ok) {
                        const data = await res.json();
                        if (!data.id) data.id = slug;
                        // Normalize ID: replace underscores with hyphens to match expected format (e.g., defaults)
                        const normalizedId = data.id.replace(/_/g, '-');
                        data.id = normalizedId;
                        religions.push(data);
                    }
                } catch (e) { /* ignore */ }
            }
            if (religions.length === 0) {
                religions = DEFAULT_RELIGIONS;
                state.usingFallback = true;
                showToast(i18nText("feature.patrons.noReligionFilesFoundUsingDefaults", null, "⚠️ No religion files found. Using defaults."), 'warning');
            }
            state.religions = mergePatronLibrary(religions, getState().patrons?.religions).sort(sortByName);

            state.dataLoaded = true;
            savePatronData();
 
        } catch (error) {
            console.warn('Failed to load remote patrons:', error);
            loadDefaultPatrons();
            showToast(i18nText("feature.patrons.errorLoadingPatronsUsingDefaults", null, "⚠️ Error loading patrons. Using defaults."), 'error');
        } finally {
            state.isLoading = false;
        }
    })();

    try {
        await loadingPromise;
    } finally {
        loadingPromise = null;
    }
}
 
function loadDefaultPatrons() {
    const saved = getState().patrons || {};
    state.cosmicPatrons = mergePatronLibrary(DEFAULT_COSMIC_PATRONS.map(normalizePatron), saved.cosmic).sort(sortByName);
    state.terrestrialPatrons = mergePatronLibrary(DEFAULT_TERRESTRIAL_PATRONS.map(normalizePatron), saved.terrestrial).sort(sortByName);
    state.religions = mergePatronLibrary(DEFAULT_RELIGIONS, saved.religions).sort(sortByName);
    state.dataLoaded = true;
    state.usingFallback = true;
    console.log(`📦 Using defaults: ${state.cosmicPatrons.length} cosmic, ${state.terrestrialPatrons.length} terrestrial, ${state.religions.length} religions`);
}
 
function savePatronData() {
    const saved = getState();
    if (!saved.patrons) saved.patrons = {};
    saved.patrons.cosmic = state.cosmicPatrons;
    saved.patrons.terrestrial = state.terrestrialPatrons;
    saved.patrons.religions = state.religions;
    saved.patrons.obligation = state.obligation;
    saved.patrons._schemaVersion = PATRON_SCHEMA_VERSION;
    saveState();
}
 
